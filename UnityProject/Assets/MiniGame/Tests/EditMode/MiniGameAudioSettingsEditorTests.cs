using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using MiniGame.UnityHost.Editor;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using Object = UnityEngine.Object;

namespace MiniGame.UnityHost.Tests
{
    public sealed class MiniGameAudioSettingsEditorTests
    {
        private const string FolderKey = "MiniGame.Audio.SourceFolder";
        private const string RecursiveKey = "MiniGame.Audio.SourceFolderRecursive";
        private string token, tempFolder, sourceFile, duplicateFile, childFile, unsupportedFile, profilePath;
        private string savedFolder;
        private bool hadFolder, hadRecursive, savedRecursive;
        private readonly HashSet<string> generatedHashes = new HashSet<string>();
        private readonly Dictionary<FieldInfo, object> browserState = new Dictionary<FieldInfo, object>();
        private MiniGameAudioProfile original, profile;
        private string originalJson;

        [SetUp]
        public void SetUp()
        {
            hadFolder = EditorPrefs.HasKey(FolderKey);
            hadRecursive = EditorPrefs.HasKey(RecursiveKey);
            savedFolder = EditorPrefs.GetString(FolderKey, "");
            savedRecursive = EditorPrefs.GetBool(RecursiveKey, false);
            var browser = typeof(MiniGameAudioSettingsWindow).Assembly.GetType("MiniGame.UnityHost.Editor.MiniGameAudioFileBrowser", true);
            foreach (string name in new[] { "folder", "recursive", "candidates", "choices", "<Warning>k__BackingField" })
            {
                var field = browser.GetField(name, BindingFlags.Static | BindingFlags.NonPublic);
                Assert.That(field, Is.Not.Null);
                browserState.Add(field, field.GetValue(null));
            }
            original = AssetDatabase.LoadAssetAtPath<MiniGameAudioProfile>(MiniGameAudioSetup.ProfilePath);
            Assert.That(original, Is.Not.Null, "Install the default audio assets before running these tests; tests never create or modify the default profile.");
            originalJson = JsonUtility.ToJson(original);
            token = Guid.NewGuid().ToString("N");
            tempFolder = Path.Combine(Path.GetTempPath(), "MiniGameAudioSettingsTests-" + token);
            Assert.That(Directory.Exists(tempFolder), Is.False);
            Directory.CreateDirectory(tempFolder);
            Directory.CreateDirectory(Path.Combine(tempFolder, "Child"));
            Directory.CreateDirectory(Path.Combine(tempFolder, "Library"));
            sourceFile = WriteWave(Path.Combine(tempFolder, "main-" + token + ".wav"), 0);
            duplicateFile = Path.Combine(tempFolder, "same-bytes-other-name-" + token + ".wav");
            File.Copy(sourceFile, duplicateFile);
            childFile = WriteWave(Path.Combine(tempFolder, "Child", "child-" + token + ".wav"), 1);
            WriteWave(Path.Combine(tempFolder, "Library", "ignored-" + token + ".wav"), 2);
            unsupportedFile = Path.Combine(tempFolder, "notes.txt");
            File.WriteAllText(unsupportedFile, token);
            profilePath = "Assets/MiniGame/Tests/AudioSettingsTest-" + token + ".asset";
            foreach (string digest in generatedHashes)
                Assert.That(FindGeneratedImports(digest), Is.Empty, "Randomized PCM bytes must not collide with an existing user's audio.");
        }

        [TearDown]
        public void TearDown()
        {
            try
            {
                if (profile != null) Undo.ClearUndo(profile);
                if (!string.IsNullOrEmpty(profilePath) && AssetDatabase.LoadMainAssetAtPath(profilePath) != null)
                {
                    Assert.That(Path.GetFileNameWithoutExtension(profilePath), Is.EqualTo("AudioSettingsTest-" + token));
                    Assert.That(AssetDatabase.DeleteAsset(profilePath), Is.True);
                    profile = null;
                }
                foreach (string digest in generatedHashes)
                    foreach (string assetPath in FindGeneratedImports(digest))
                    {
                        Assert.That(Hash(assetPath), Is.EqualTo(digest), "Only this fixture's exact generated bytes may be removed.");
                        Assert.That(Path.GetFileName(assetPath), Does.Contain(token));
                        Assert.That(AssetDatabase.DeleteAsset(assetPath), Is.True);
                    }
                if (!string.IsNullOrEmpty(tempFolder) && Directory.Exists(tempFolder))
                {
                    string expected = Path.GetFullPath(Path.Combine(Path.GetTempPath(), "MiniGameAudioSettingsTests-" + token));
                    string actual = Path.GetFullPath(tempFolder);
                    Assert.That(Guid.TryParseExact(token, "N", out _), Is.True);
                    Assert.That(actual, Is.EqualTo(expected));
                    Assert.That(actual.StartsWith(Path.GetFullPath(Path.GetTempPath()).TrimEnd(Path.DirectorySeparatorChar)
                        + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase), Is.True);
                    Assert.That((File.GetAttributes(actual) & FileAttributes.ReparsePoint) == 0, Is.True);
                    Directory.Delete(actual, true);
                }
            }
            finally
            {
                if (hadFolder) EditorPrefs.SetString(FolderKey, savedFolder); else EditorPrefs.DeleteKey(FolderKey);
                if (hadRecursive) EditorPrefs.SetBool(RecursiveKey, savedRecursive); else EditorPrefs.DeleteKey(RecursiveKey);
                foreach (var item in browserState) item.Key.SetValue(null, item.Value);
                browserState.Clear();
                generatedHashes.Clear();
            }
            if (original != null) Assert.That(JsonUtility.ToJson(original), Is.EqualTo(originalJson), "Tests must preserve the real profile.");
        }

        [Test]
        public void FolderPickerListsOnlySupportedFilesAndImportsNothingUntilAssignment()
        {
            var before = ImportedFiles();
            var top = MiniGameAudioSettingsWindow.SelectSourceFolder(tempFolder);
            Assert.That(top, Is.EquivalentTo(new[] { sourceFile, duplicateFile }));
            var recursive = MiniGameAudioSettingsWindow.SelectSourceFolder(tempFolder, true);
            Assert.That(recursive, Is.EquivalentTo(new[] { sourceFile, duplicateFile, childFile }));
            Assert.That(ImportedFiles(), Is.EqualTo(before), "Selecting a folder must never batch-import its files.");
        }

        [Test]
        public void AssignExternalFilePreservesBytesDeduplicatesAndSupportsUndoSaveReload()
        {
            profile = Object.Instantiate(original);
            AssetDatabase.CreateAsset(profile, profilePath);
            const MiniGameSound role = MiniGameSound.UIInteraction;
            var initialClip = profile.GetClip(role);
            string sourceHash = Hash(sourceFile);
            Undo.IncrementCurrentGroup();
            int group = Undo.GetCurrentGroup();
            var imported = MiniGameAudioSettingsWindow.AssignCandidate(profile, role, sourceFile);
            var importedPath = AssetDatabase.GetAssetPath(imported);
            Assert.That(imported, Is.Not.Null);
            Assert.That(profile.GetClip(role), Is.SameAs(imported));
            Assert.That(profile.GetClip(MiniGameSound.Gameplay), Is.SameAs(original.GetClip(MiniGameSound.Gameplay)));
            Assert.That(importedPath, Does.StartWith(MiniGameAudioSetup.ImportedPath + "/"));
            Assert.That(Hash(importedPath), Is.EqualTo(sourceHash));
            Assert.That(Hash(sourceFile), Is.EqualTo(sourceHash), "Importing must not rewrite the selected source file.");
            Assert.That(((AudioImporter)AssetImporter.GetAtPath(importedPath)).defaultSampleSettings.loadType,
                Is.EqualTo(AudioClipLoadType.DecompressOnLoad));
            Undo.FlushUndoRecordObjects();
            Undo.CollapseUndoOperations(group);
            Undo.PerformUndo();
            Assert.That(profile.GetClip(role), Is.SameAs(initialClip));
            Undo.PerformRedo();
            Assert.That(profile.GetClip(role), Is.SameAs(imported));
            var duplicate = MiniGameAudioSetup.ImportSelectedFile(duplicateFile, role);
            Assert.That(AssetDatabase.GetAssetPath(duplicate), Is.EqualTo(importedPath));
            Assert.That(FindGeneratedImports(sourceHash).Length, Is.EqualTo(1));
            string clipGuid = AssetDatabase.AssetPathToGUID(importedPath);
            Assert.That(clipGuid, Is.Not.Empty);
            AssetDatabase.SaveAssetIfDirty(profile);
            Undo.ClearUndo(profile);
            Resources.UnloadAsset(profile);
            profile = AssetDatabase.LoadAssetAtPath<MiniGameAudioProfile>(profilePath);
            Assert.That(profile, Is.Not.Null);
            using (var serialized = new SerializedObject(profile))
            {
                var sounds = serialized.FindProperty("Sounds");
                SerializedProperty savedClip = null;
                for (int index = 0; index < sounds.arraySize; index++)
                {
                    var entry = sounds.GetArrayElementAtIndex(index);
                    if (entry.FindPropertyRelative("Id").intValue == (int)role) savedClip = entry.FindPropertyRelative("Clip");
                }
                Assert.That(savedClip, Is.Not.Null);
                Assert.That(AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(savedClip.objectReferenceValue)), Is.EqualTo(clipGuid));
            }
        }

        [Test]
        public void UnsupportedFileIsRejectedBeforeAnyImport()
        {
            bool directoryExisted = Directory.Exists(MiniGameAudioSetup.ImportedPath);
            var before = ImportedFiles();
            Assert.Throws<NotSupportedException>(() => MiniGameAudioSetup.ImportSelectedFile(unsupportedFile, MiniGameSound.UIInteraction));
            Assert.That(ImportedFiles(), Is.EqualTo(before));
            Assert.That(Directory.Exists(MiniGameAudioSetup.ImportedPath), Is.EqualTo(directoryExisted));
        }

        [Test]
        public void EnsuringExistingDefaultAssetsPreservesTheRealProfile()
        {
            string mixerPath = AssetDatabase.GetAssetPath(original.Mixer);
            string mixerHash = Hash(mixerPath);
            var result = MiniGameAudioSetup.EnsureAssets();
            Assert.That(result, Is.SameAs(original));
            Assert.That(JsonUtility.ToJson(result), Is.EqualTo(originalJson));
            Assert.That(Hash(mixerPath), Is.EqualTo(mixerHash));
        }

        private string WriteWave(string path, int variant)
        {
            const int sampleRate = 22050, samples = 2205;
            byte[] nonce = Guid.ParseExact(token, "N").ToByteArray();
            using (var stream = File.Create(path))
            using (var writer = new BinaryWriter(stream, Encoding.ASCII))
            {
                writer.Write(Encoding.ASCII.GetBytes("RIFF")); writer.Write(36 + samples * 2);
                writer.Write(Encoding.ASCII.GetBytes("WAVEfmt ")); writer.Write(16);
                writer.Write((short)1); writer.Write((short)1); writer.Write(sampleRate);
                writer.Write(sampleRate * 2); writer.Write((short)2); writer.Write((short)16);
                writer.Write(Encoding.ASCII.GetBytes("data")); writer.Write(samples * 2);
                for (int index = 0; index < samples; index++)
                    writer.Write((short)((index % 32 < 16 ? 1 : -1) * (256 + nonce[index % nonce.Length] + variant * 300)));
            }
            generatedHashes.Add(Hash(path));
            return path;
        }

        private static string Hash(string path)
        {
            using (var hash = SHA256.Create())
            using (var stream = File.OpenRead(path))
                return BitConverter.ToString(hash.ComputeHash(stream)).Replace("-", "").ToLowerInvariant();
        }

        private static string[] ImportedFiles() => Directory.Exists(MiniGameAudioSetup.ImportedPath)
            ? Directory.GetFiles(MiniGameAudioSetup.ImportedPath).OrderBy(path => path, StringComparer.Ordinal).ToArray()
            : Array.Empty<string>();

        private static string[] FindGeneratedImports(string digest) => Directory.Exists(MiniGameAudioSetup.ImportedPath)
            ? Directory.GetFiles(MiniGameAudioSetup.ImportedPath, "*_" + digest + ".*")
                .Where(MiniGameAudioSetup.IsSupportedAudioFile).Select(path => path.Replace('\\', '/')).ToArray()
            : Array.Empty<string>();
    }
}
